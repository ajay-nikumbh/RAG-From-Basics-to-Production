"""
Usage and cost tracking.

This file measures how many tokens each pipeline run uses and what it costs.
A run (one query or one ingestion) opens a UsageMeter with track_usage().
While the run is active, the embedder and the generator add the token counts
returned by Azure OpenAI to that meter. When the run finishes, one event is
appended to data/usage/usage.jsonl with the tokens, the cost in US dollars,
the duration and a little context (the question or the file name).

A query also splits its usage by pipeline stage (rewrite, retrieve, rerank,
compress, generate) with track_stage(), so each event records the tokens,
cost and time of every stage. summarize() turns the events into the totals,
daily series, average cost and time per stage, and recent list shown on the
analytics page. Runs are of three families: questions (query),
ingestions (ingest) and evaluations (every kind starting with "eval").
"""

# Imports
from app.core.config import Settings, get_settings
from dataclasses import dataclass, field
from datetime import datetime, timezone
from contextlib import contextmanager
from collections import defaultdict
from contextvars import ContextVar
import threading
import json
import time


# Only one thread writes to the usage file at a time
WRITE_LOCK = threading.Lock()


@dataclass
class UsageMeter:
    """Token counts collected during one pipeline run."""

    # Tokens sent to the embedding model
    embedding_tokens: int = 0

    # Tokens sent to and generated by the chat model
    prompt_tokens: int = 0
    completion_tokens: int = 0

    # Extra facts learned during the run, saved with the event (for example chunks)
    details: dict = field(default_factory=dict)

    # Tokens, cost and time per pipeline stage, filled by track_stage()
    stages: dict = field(default_factory=dict)

    def cost(self, settings: Settings) -> float:
        """Price of this run in US dollars, from the per-million-token prices."""

        # Each token type has its own price per one million tokens
        return (
            self.embedding_tokens * settings.price_embedding_per_million
            + self.prompt_tokens * settings.price_chat_input_per_million
            + self.completion_tokens * settings.price_chat_output_per_million
        ) / 1_000_000


# Meter of the run in progress, or None outside a run
current_meter: ContextVar[UsageMeter | None] = ContextVar("current_meter", default=None)


def add_embedding_tokens(tokens: int) -> None:
    """Add embedding tokens to the active run, if any."""

    # Calls outside a run (for example in tests) are not counted
    meter = current_meter.get()
    if meter:
        meter.embedding_tokens += tokens


def add_chat_tokens(prompt_tokens: int, completion_tokens: int) -> None:
    """Add chat tokens to the active run, if any."""

    # Calls outside a run are not counted
    meter = current_meter.get()
    if meter:
        meter.prompt_tokens += prompt_tokens
        meter.completion_tokens += completion_tokens


@contextmanager
def track_usage(kind: str, **context):
    """Measure tokens and time of one run and save it as an event when it succeeds.

        with track_usage("query", question=question) as meter:
            ...
            meter.cost(settings)
    """

    # Start a fresh meter for this run
    meter = UsageMeter()
    token = current_meter.set(meter)
    start = time.perf_counter()

    # Run the block; failed runs are not saved
    try:
        yield meter
    finally:
        current_meter.reset(token)

    # Save the finished run
    record_event(kind, meter, round((time.perf_counter() - start) * 1000), context)


@contextmanager
def track_stage(meter: UsageMeter, name: str):
    """Record the tokens, cost and time one stage of a run adds to the meter.

        with track_stage(meter, "rerank"):
            outcome = rerank(question, candidates)
    """

    # Totals before the stage and the start time
    settings = get_settings()
    before = (meter.embedding_tokens, meter.prompt_tokens, meter.completion_tokens)
    cost_before = meter.cost(settings)
    start = time.perf_counter()

    # Run the stage
    yield

    # The difference is what this stage used
    meter.stages[name] = {
        "embedding_tokens": meter.embedding_tokens - before[0],
        "prompt_tokens": meter.prompt_tokens - before[1],
        "completion_tokens": meter.completion_tokens - before[2],
        "cost_usd": round(meter.cost(settings) - cost_before, 8),
        "latency_ms": round((time.perf_counter() - start) * 1000),
    }


def record_event(kind: str, meter: UsageMeter, latency_ms: int, context: dict) -> dict:
    """Append one run to the usage file and return it."""

    # Read the shared settings
    settings = get_settings()

    # One flat record per run
    event = {
        "time": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "kind": kind,
        "embedding_tokens": meter.embedding_tokens,
        "prompt_tokens": meter.prompt_tokens,
        "completion_tokens": meter.completion_tokens,
        "total_tokens": meter.embedding_tokens + meter.prompt_tokens + meter.completion_tokens,
        "cost_usd": round(meter.cost(settings), 8),
        "latency_ms": latency_ms,
        **context,
        **meter.details,
    }

    # Per-stage usage, only for runs that recorded stages
    if meter.stages:
        event["stages"] = meter.stages

    # Append as one JSON line
    settings.usage_file.parent.mkdir(parents=True, exist_ok=True)
    with WRITE_LOCK, settings.usage_file.open("a", encoding="utf-8") as file:
        file.write(json.dumps(event, ensure_ascii=False) + "\n")

    return event


def read_events() -> list[dict]:
    """Return every saved run, oldest first."""

    # No file yet means no usage yet
    path = get_settings().usage_file
    if not path.exists():
        return []

    # One JSON object per line
    with path.open(encoding="utf-8") as file:
        return [json.loads(line) for line in file if line.strip()]


def summarize(events: list[dict], recent_limit: int = 50) -> dict:
    """Build totals, a daily series and the most recent runs."""

    # Totals over all runs
    queries = [e for e in events if e["kind"] == "query"]
    totals = {
        "queries": len(queries),
        "ingestions": sum(1 for e in events if e["kind"] == "ingest"),
        "evals": sum(1 for e in events if e["kind"].startswith("eval")),
        "embedding_tokens": sum(e["embedding_tokens"] for e in events),
        "prompt_tokens": sum(e["prompt_tokens"] for e in events),
        "completion_tokens": sum(e["completion_tokens"] for e in events),
        "total_tokens": sum(e["total_tokens"] for e in events),
        "cost_usd": round(sum(e["cost_usd"] for e in events), 6),
        "avg_query_latency_ms": round(sum(e["latency_ms"] for e in queries) / len(queries)) if queries else 0,
    }

    # Cost, tokens and run counts per day (UTC date)
    days = defaultdict(lambda: {"cost_usd": 0.0, "tokens": 0, "queries": 0, "ingestions": 0, "evals": 0})
    counters = {"query": "queries", "ingest": "ingestions"}
    for event in events:
        day = days[event["time"][:10]]
        day["cost_usd"] += event["cost_usd"]
        day["tokens"] += event["total_tokens"]
        day[counters.get(event["kind"], "evals")] += 1
    daily = [{"date": date, **values, "cost_usd": round(values["cost_usd"], 6)} for date, values in sorted(days.items())]

    # Average cost and time per stage over the questions that recorded stages, in pipeline order
    staged = [e for e in queries if e.get("stages")]
    stage_names = list(dict.fromkeys(name for e in staged for name in e["stages"]))
    stages = {}
    for name in stage_names:
        values = [e["stages"][name] for e in staged if name in e["stages"]]
        stages[name] = {
            "runs": len(values),
            "avg_cost_usd": round(sum(v["cost_usd"] for v in values) / len(values), 8),
            "avg_tokens": round(sum(v["prompt_tokens"] + v["completion_tokens"] + v["embedding_tokens"] for v in values) / len(values)),
            "avg_latency_ms": round(sum(v["latency_ms"] for v in values) / len(values)),
        }

    # Newest runs first
    recent = list(reversed(events[-recent_limit:]))

    return {"totals": totals, "daily": daily, "stages": stages, "recent": recent}
